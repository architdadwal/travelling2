-- Himalayan Trails / Supabase schema
-- Run this in Supabase SQL Editor.
-- IMPORTANT: this implementation uses Supabase Auth with a generated internal email
-- so customers can log in with username + password without entering an email.
-- Passwords are never stored in application tables.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  full_name text,
  phone text,
  email text,
  starting_location text,
  preferred_travel_date date,
  travellers integer default 1 check (travellers > 0),
  adults integer default 1 check (adults >= 0),
  children integer default 0 check (children >= 0),
  budget text,
  preferences text,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.destinations (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  description text,
  image_url text,
  category text not null default 'destination',
  featured boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  description text,
  duration text,
  image_url text,
  category text not null,
  destination text,
  itinerary jsonb not null default '[]'::jsonb,
  inclusions jsonb not null default '[]'::jsonb,
  exclusions jsonb not null default '[]'::jsonb,
  price_from numeric(12,2),
  featured boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  package_id bigint references public.packages(id) on delete set null,
  destination_id bigint references public.destinations(id) on delete set null,
  travel_date date,
  travellers integer not null default 1,
  notes text,
  status text not null default 'new' check (status in ('new','contacted','confirmed','cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists bookings_user_id_idx on public.bookings(user_id);
create index if not exists bookings_status_idx on public.bookings(status);

alter table public.profiles enable row level security;
alter table public.destinations enable row level security;
alter table public.packages enable row level security;
alter table public.bookings enable row level security;

create policy "public can read destinations"
on public.destinations for select using (true);

create policy "public can read packages"
on public.packages for select using (true);

create policy "users can read own profile"
on public.profiles for select using (auth.uid() = id);

create policy "users can update own profile"
on public.profiles for update using (auth.uid() = id);

create policy "users can insert own profile"
on public.profiles for insert with check (auth.uid() = id);

create policy "users can read own bookings"
on public.bookings for select using (auth.uid() = user_id);

create policy "users can create own bookings"
on public.bookings for insert with check (auth.uid() = user_id);

-- Admin policies use the profile role. This is intentionally kept simple for this starter.
create policy "admins can read all profiles"
on public.profiles for select
using (
  auth.uid() = id OR exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
  )
);

create policy "admins can read all bookings"
on public.bookings for select
using (
  auth.uid() = user_id OR exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
  )
);

create policy "admins can update bookings"
on public.bookings for update
using (
  exists (
    select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
  )
);

